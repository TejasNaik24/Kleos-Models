#!/usr/bin/env python3
"""Prepare, normalize and describe a KLEOS dataset.

Three modes:

``--generate-fixtures``
    Write the synthetic development fixtures in ``data/examples/``. Deterministic,
    so regenerating produces byte-identical files.

``--emit-schemas``
    Regenerate ``data/schema/*.schema.json`` from the pydantic models, keeping the
    published JSON Schema and the code from drifting apart.

default
    Read raw JSONL, validate it, and write a versioned dataset directory with a
    manifest.

Usage::

    python scripts/prepare_dataset.py --generate-fixtures
    python scripts/prepare_dataset.py --emit-schemas
    python scripts/prepare_dataset.py --input raw.jsonl --output data/processed/v1 \\
                                      --version kleos-policy-v0.1.0
"""

