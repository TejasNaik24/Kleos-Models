def prepare(input_path: Path, output_dir: Path, version: str, *, strict: bool) -> int:
    """Validate a raw JSONL file and write a versioned dataset directory."""
    if output_dir.exists() and any(output_dir.iterdir()):
        logger.error(
            "Output directory %s already exists and is not empty. Dataset versions are "
            "immutable — silently overwriting one breaks every comparison that "
            "referenced it. Choose a new --version.",
            output_dir,
        )
        return 1

    examples, load_report = load_examples(input_path, model=TrainingExample, strict=strict)
    logger.info("%s", load_report.summary())

    report = validate_examples(examples, split_name=input_path.name)
    print(report.render())
    if not report.ok:
        logger.error("Validation failed; dataset not written.")
        return 1

    output_dir.mkdir(parents=True, exist_ok=True)
    train_path = output_dir / "train.jsonl"
    write_jsonl(examples, train_path)

    manifest = DatasetManifest(
        version=version,
        source="prepared",
        description=f"Prepared from {input_path.name}",
        example_count=len(examples),
        splits=SplitCounts(train=len(examples)),
        task_distribution=dict(Counter(e.task for e in examples).most_common()),
        domain_distribution=dict(Counter(e.variation_axes.domain for e in examples).most_common()),
        file_hashes={"train.jsonl": file_sha256(train_path)},
    ).finalize()

    (output_dir / "manifest.json").write_text(
        json.dumps(manifest.model_dump(mode="json"), indent=2), encoding="utf-8"
    )
    logger.info("Wrote dataset version %s to %s", version, output_dir)
    print(f"\n✓ Prepared {len(examples)} example(s) as {version} in {output_dir}")
    print("\nNext: python scripts/split_dataset.py --dataset", output_dir)
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description="Prepare, normalize or generate a KLEOS dataset.",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--input", type=Path, help="Raw JSONL file to prepare.")
    parser.add_argument("--output", type=Path, help="Output dataset directory.")
    parser.add_argument("--version", default="kleos-policy-v0.1.0", help="Dataset version.")
    parser.add_argument(
        "--generate-fixtures",
        action="store_true",
        help="Write the synthetic development fixtures to data/examples/.",
    )
    parser.add_argument(
        "--emit-schemas",
        action="store_true",
        help="Regenerate data/schema/*.schema.json from the pydantic models.",
    )
    parser.add_argument(
        "--no-strict",
        action="store_true",
        help="Report every invalid example instead of stopping at the first.",
    )
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    from kleos_models.logging_utils import resolve_level

    configure_logging(level=resolve_level(verbose=args.verbose))

    if args.generate_fixtures:
        paths = write_fixtures(REPO_ROOT / "data" / "examples")
        print("\n✓ Generated development fixtures:")
        for name, path in paths.items():
            print(f"    {name:10} {path.relative_to(REPO_ROOT)}")
        print("\n  These are development fixtures, NOT the KLEOS research dataset.")
        return 0

    if args.emit_schemas:
        written = emit_schemas(REPO_ROOT / "data" / "schema")
        print("\n✓ Emitted JSON Schemas:")
        for path in written.values():
            print(f"    {path.relative_to(REPO_ROOT)}")
        return 0

    if not args.input or not args.output:
        parser.error("--input and --output are required unless generating fixtures or schemas")

    return prepare(args.input, args.output, args.version, strict=not args.no_strict)


if __name__ == "__main__":
    raise SystemExit(main())
