#: Fixed creation timestamp for the fixtures.
#
# The fixtures must regenerate byte-identically — CI checks that the committed
# files still match their generator. A live `datetime.now()` would make the
# manifest differ on every run and turn that check into permanent noise.
# Bump this only when the fixture content itself changes.
FIXTURE_CREATED_AT = "2026-08-14T00:00:00+00:00"

FIXTURE_WARNING = (
    "SYNTHETIC DEVELOPMENT FIXTURE. Generated by scripts/prepare_dataset.py "
    "--generate-fixtures. Not the KLEOS research dataset."
)

SYSTEM_PROMPT = (
    "You are the reasoning layer of KLEOS. Deterministic systems have already "
    "retrieved and ranked the context. Decide, then justify from the evidence "
    "provided. Do not invent facts."
)


def _prioritization_examples() -> list[dict]:
    """Notification-prioritization fixtures.

    Each teaches the *policy* "prefer the closest deadline with the strongest
    evidence of impact", never a fact about a particular person or company
    (spec section 9).
    """
    scenarios = [
        {
            "family": "deadline-vs-evidence-01",
            "domain": "career",
            "items": [
                ("internship-application", "closes in 2 days", "strong", "confirmed opening"),
                ("networking-event", "in 3 weeks", "weak", "no confirmed attendees"),
                ("resume-review", "no deadline", "medium", "peer feedback offered"),
            ],
            "answer": ["internship-application", "resume-review", "networking-event"],
        },
        {
            "family": "deadline-vs-evidence-02",
            "domain": "research",
            "items": [
                ("conference-abstract", "due tomorrow", "strong", "advisor confirmed support"),
                ("literature-review", "due in 10 days", "medium", "partially drafted"),
                ("lab-social", "this evening", "weak", "optional attendance"),
            ],
            "answer": ["conference-abstract", "literature-review", "lab-social"],
        },
        {
            "family": "deadline-vs-evidence-03",
            "domain": "coursework",
            "items": [
                ("problem-set", "due in 6 hours", "strong", "graded, 15% of final"),
                ("group-project-checkin", "due in 4 days", "strong", "teammates blocked"),
                ("optional-reading", "no deadline", "weak", "supplementary"),
            ],
            "answer": ["problem-set", "group-project-checkin", "optional-reading"],
        },
        {
            "family": "urgency-vs-impact-01",
            "domain": "projects",
            "items": [
                ("production-bug", "ongoing", "strong", "blocks all users"),
                ("feature-request", "due in 2 days", "medium", "one requester"),
                ("refactor-proposal", "no deadline", "weak", "no measured benefit"),
            ],
            "answer": ["production-bug", "feature-request", "refactor-proposal"],
        },
    ]

    examples: list[dict] = []
    for index, scenario in enumerate(scenarios, start=1):
        listing = "\n".join(
            f"- {name}: deadline {deadline}; evidence {quality} ({detail})"
            for name, deadline, quality, detail in scenario["items"]
        )
        answer_list = "\n".join(
            f"{rank}. {name}" for rank, name in enumerate(scenario["answer"], start=1)
        )
        top = scenario["answer"][0]
        top_detail = next(i for i in scenario["items"] if i[0] == top)

        examples.append(
            {
                "id": f"fixture-prior-{index:04d}",
                "version": DATASET_SCHEMA_VERSION,
                "task": "notification_prioritization",
                "messages": [
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {
                        "role": "user",
                        "content": (
                            f"Rank these items by what deserves attention first.\n\n{listing}"
                        ),
                    },
                    {
                        "role": "assistant",
                        "content": (
                            f"{answer_list}\n\n"
                            f"Reasoning: {top} comes first because its deadline is the "
                            f"nearest ({top_detail[1]}) and the evidence of impact is "
                            f"{top_detail[2]} ({top_detail[3]}). Items with weak evidence "
                            "or no deadline rank last, since acting on them displaces "
                            "work with a firm cost of delay."
                        ),
                    },
                ],
                "variation_axes": {
                    "domain": scenario["domain"],
                    # Alternate the entity-set label so entity_holdout splitting
                    # and coverage reporting have something to partition on.
                    "entities": "set_a" if index % 2 else "set_b",
                    "urgency": "high" if index % 2 else "medium",
                    "deadlines": "mixed",
                    "evidence_quality": "mixed",
                    "conflicting_evidence": "none",
                    "context_length": "short",
                    "presentation_order": "as_given",
                    "format": "bullets",
                    "difficulty": "easy" if index <= 2 else "medium",
                    "ambiguity": "low",
                },
                "metadata": {
                    "source": "development_fixture",
                    "quality_status": "reviewed",
                    "scenario_family": scenario["family"],
                    "author": "fixture_generator",
                    "notes": FIXTURE_WARNING,
                },
            }
        )
    return examples


