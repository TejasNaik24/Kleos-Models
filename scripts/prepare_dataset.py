def write_fixtures(output_dir: Path) -> dict[str, Path]:
    """Write the synthetic fixtures and their manifest."""
    output_dir.mkdir(parents=True, exist_ok=True)

    train_raw = generate_training_fixtures()
    eval_raw = generate_evaluation_fixtures()

    # Validate before writing: a fixture that violates the contract would make
    # every downstream test meaningless.
    train_examples = [TrainingExample.model_validate(e) for e in train_raw]
    eval_examples = [EvaluationExample.model_validate(e) for e in eval_raw]

    train_path = output_dir / "synthetic_train.jsonl"
    eval_path = output_dir / "synthetic_eval.jsonl"
    write_jsonl(train_examples, train_path)
    write_jsonl(eval_examples, eval_path)

    manifest = DatasetManifest(
        version="kleos-dev-fixtures-v0.1.0",
        schema_version=DATASET_SCHEMA_VERSION,
        preprocessing_version=PREPROCESSING_VERSION,
        created_at=FIXTURE_CREATED_AT,
        source="synthetic",
        description=(
            "Synthetic development fixtures for exercising the KLEOS pipeline. "
            "NOT the KLEOS research dataset. Generated deterministically by "
            "scripts/prepare_dataset.py --generate-fixtures."
        ),
        example_count=len(train_examples),
        splits=SplitCounts(train=len(train_examples)),
        task_distribution=dict(Counter(e.task for e in train_examples).most_common()),
        domain_distribution=dict(
            Counter(e.variation_axes.domain for e in train_examples).most_common()
        ),
        source_distribution=dict(Counter(e.metadata.source for e in train_examples).most_common()),
        quality_distribution=dict(
            Counter(e.metadata.quality_status for e in train_examples).most_common()
        ),
        file_hashes={
            "synthetic_train.jsonl": file_sha256(train_path),
            "synthetic_eval.jsonl": file_sha256(eval_path),
        },
        contains_private_data=False,
        notes=FIXTURE_WARNING,
    ).finalize()

    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(manifest.model_dump(mode="json"), indent=2), encoding="utf-8"
    )

    logger.info(
        "Wrote %d training and %d evaluation fixture(s) to %s",
        len(train_examples),
        len(eval_examples),
        output_dir,
    )
    return {"train": train_path, "eval": eval_path, "manifest": manifest_path}


